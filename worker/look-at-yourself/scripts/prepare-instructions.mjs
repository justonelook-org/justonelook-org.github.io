import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const sources = [
  ["../../../bots/look-at-yourself/instructions.md", "../src/generated-instructions.js"],
  ["../../../bots/self-directed-attention-exercise/instructions.md", "../src/generated-sda-instructions.js"]
];

for (const [source, target] of sources) {
  const instructions = await readFile(fileURLToPath(new URL(source, import.meta.url)), "utf8");
  const generated = `// Generated from ${source}. Do not edit this file.\nexport default ${JSON.stringify(instructions)};\n`;
  await writeFile(fileURLToPath(new URL(target, import.meta.url)), generated, "utf8");
}
